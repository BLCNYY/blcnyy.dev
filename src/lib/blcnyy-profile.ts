function toLabel(value: string) {
  return value
    .replace(/([A-Z])/g, " $1")
    .replace(/^./, (character) => character.toUpperCase());
}

function recordSection(title: string, values: Record<string, string>) {
  return [
    `## ${title}`,
    ...Object.entries(values).map(([key, value]) => `${toLabel(key)}: ${value}`),
    "",
  ];
}

function listSection(title: string, values: readonly string[]) {
  return [`## ${title}`, ...values.map((value) => `- ${value}`), ""];
}

function getDateParts(date: Date) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: PROFILE_TIME_ZONE,
    year: "numeric",
    month: "numeric",
    day: "numeric",
  }).formatToParts(date);

  return {
    year: Number(parts.find((part) => part.type === "year")?.value),
    month: Number(parts.find((part) => part.type === "month")?.value),
    day: Number(parts.find((part) => part.type === "day")?.value),
  };
}

function formatLongDate(date: Date) {
  return new Intl.DateTimeFormat("en-US", {
    timeZone: PROFILE_TIME_ZONE,
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(date);
}

function isValidBirthDate(birthDate: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(birthDate)) {
    return false;
  }

  const date = new Date(`${birthDate}T00:00:00Z`);

  return (
    !Number.isNaN(date.getTime()) &&
    date.toISOString().slice(0, 10) === birthDate
  );
}

function calculateAge(birthDate: string, asOfDate: Date) {
  const [birthYear, birthMonth, birthDay] = birthDate
    .split("-")
    .map((value) => Number(value));
  const currentDate = getDateParts(asOfDate);
  let age = currentDate.year - birthYear;

  if (
    currentDate.month < birthMonth ||
    (currentDate.month === birthMonth && currentDate.day < birthDay)
  ) {
    age -= 1;
  }

  return age;
}

function ageFactsSection(asOfDate: Date) {
  const currentDate = formatLongDate(asOfDate);
  const birthDate = process.env.PROFILE_BIRTH_DATE?.trim();

  return [
    "## Current Date And Age Facts",
    `Current date for age calculations: ${currentDate} (${PROFILE_TIME_ZONE}).`,
    ...(birthDate && isValidBirthDate(birthDate)
      ? [
          `Ömer Balkan was born on ${birthDate}, so he is ${calculateAge(birthDate, asOfDate)} years old as of ${currentDate}.`,
        ]
      : []),
    "",
  ];
}

